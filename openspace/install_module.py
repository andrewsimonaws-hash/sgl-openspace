"""Copy the Sgl module (module_sgl/, the source of truth) into an OpenSpace 0.22 source tree.

    python install_module.py [openspace_src] [--backport-text-alpha]
    cmake -S <src> -B <build>                     # first time only; modules are on by default
    cmake --build <build> --config RelWithDebInfo --parallel

openspace_src defaults to the OPENSPACE_SRC environment variable. Codegen output
(*_codegen.cpp) is regenerated by the build, so it isn't copied.

--backport-text-alpha: OpenSpace 0.22 draws ScreenSpaceText into an RGB texture, so every
caption and label sits on an opaque black box, which shows wherever it overlaps the Earth or
the Sun. OpenSpace's master branch already creates that texture as RGBA; this flag applies the
same one-line change to 0.22. The module itself runs without it.
"""
import argparse
import os
import shutil
import sys

import paths

HERE = os.path.dirname(os.path.abspath(__file__))
MODULE = os.path.join(HERE, "module_sgl")
RGB, RGBA = ".format = ghoul::opengl::Texture::Format::RGB,", ".format = ghoul::opengl::Texture::Format::RGBA,"


def backport_text_alpha(src):
    text = os.path.join(src, "src", "rendering", "screenspacerenderabletext.cpp")
    with open(text, encoding="utf-8", newline="") as f:
        code = f.read()
    if RGBA in code:
        print("already RGBA:", text)
    elif RGB in code:
        with open(text, "w", encoding="utf-8", newline="") as f:
            f.write(code.replace(RGB, RGBA))
        print("backported the RGBA text texture:", text)
    else:
        sys.exit(f"text texture format not found in {text}; is this OpenSpace 0.22?")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("openspace_src", nargs="?")
    ap.add_argument("--backport-text-alpha", action="store_true")
    args = ap.parse_args()
    src = args.openspace_src or paths.src()
    if not os.path.isfile(os.path.join(src, "support", "cmake", "module_definition.cmake")):
        sys.exit(f"{src} doesn't look like an OpenSpace source tree")

    dst = os.path.join(src, "modules", "sgl")
    shutil.copytree(MODULE, dst, dirs_exist_ok=True, ignore=shutil.ignore_patterns("*_codegen.cpp"))
    print("installed", MODULE, "->", dst)
    if args.backport_text_alpha:
        backport_text_alpha(src)


if __name__ == "__main__":
    main()
