"""Copy the Sgl module (module_sgl/, the source of truth) into the OpenSpace source tree, and
patch OpenSpace's screen-space text to keep an alpha channel.

    python install_module.py
    cmake -S <src> -B <build> -DOPENSPACE_MODULE_SGL=ON      # first time only
    cmake --build <build> --config RelWithDebInfo --parallel

Codegen output (*_codegen.cpp) is regenerated by the build, so it isn't copied.

The patch: OpenSpace 0.22 draws ScreenSpaceText into an RGB texture, so every caption and
label sits on an opaque black box, which shows wherever it overlaps the Earth or the Sun.
An RGBA texture keeps the box transparent (its framebuffer is already cleared to alpha 0).
"""
import os
import shutil

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "module_sgl")
OPENSPACE_SRC = r"C:\Users\andre\OpenSpace\src"
DST = os.path.join(OPENSPACE_SRC, "modules", "sgl")
TEXT = os.path.join(OPENSPACE_SRC, "src", "rendering", "screenspacerenderabletext.cpp")
RGB, RGBA = ".format = ghoul::opengl::Texture::Format::RGB,", ".format = ghoul::opengl::Texture::Format::RGBA,"

shutil.copytree(SRC, DST, dirs_exist_ok=True, ignore=shutil.ignore_patterns("*_codegen.cpp"))
print("installed", SRC, "->", DST)

with open(TEXT, encoding="utf-8") as f:
    code = f.read()
if RGB in code:
    with open(TEXT, "w", encoding="utf-8", newline="") as f:
        f.write(code.replace(RGB, RGBA))
    print("patched", TEXT, "(text texture RGB -> RGBA)")
elif RGBA in code:
    print("already patched", TEXT)
else:
    print("WARNING: text texture format not found in", TEXT)
